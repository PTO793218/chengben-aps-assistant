async (page) => {
  page.setDefaultTimeout(150000);
  const check=(v,m)=>{if(!v)throw new Error(m);};
  const ask=async(text)=>{await page.getByRole('textbox',{name:'输入问题',exact:true}).fill(text);await page.getByRole('button',{name:'发送消息',exact:true}).click();};
  const last=()=>page.locator('.interactive-demo').last();
  await page.getByRole('button',{name:'新建对话',exact:true}).click();
  await page.locator('.suggestion-grid button').first().waitFor();
  await ask('MRP 演示 Z9900003，无库存无在途');
  await last().getByRole('button',{name:'计算演示需求'}).waitFor();
  check(await last().locator('.demo-execution').innerText().then(t=>t.includes('大模型已参与')),'MRP preparation invoked model');
  check(await last().getByLabel('库存与在途场景').inputValue()==='none','negative input respected');
  check(await last().getByLabel('本次成品需求（件）').inputValue()==='12500','demand source');
  await last().getByRole('button',{name:'计算演示需求'}).click();
  await last().getByText('6,886.13',{exact:false}).first().waitFor();
  await last().getByRole('button',{name:'查看演示详情'}).click();
  const region=()=>page.getByRole('region',{name:'操作演示详情'});
  check(await region().locator('.demo-execution').innerText().then(t=>t.includes('大模型已参与')),'MRP confirmed calculation invoked model');
  check(await region().locator('tbody tr').count()===4,'four material layers');
  check(await region().innerText().then(t=>t.includes('0.55089')&&t.includes('6886.13')&&t.includes('生产需求')),'formula and unit evidence');
  await region().getByText('这个数量怎么算出来？').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/20261015-mrp-basis.png'});
  const cases=[['none','4,407.12'],['stock','3,407.12'],['supply','1,907.12'],['late','1,907.12'],['supply','1,907.12']];
  for(const [scenario,expected] of cases){
    await region().getByLabel('本次成品需求（件）').fill('8000');
    await region().getByLabel('库存与在途场景').selectOption(scenario);
    await region().getByRole('button',{name:'计算演示需求'}).click();
    await last().getByText(expected,{exact:false}).first().waitFor();
    check(await last().innerText().then(t=>t.includes('本次需求 8000 件')),'changed quantity applies to new result');
    await last().getByRole('button',{name:'查看演示详情'}).click();
  }
  await region().getByText('这个数量怎么算出来？').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/20261015-mrp-supply.png'});
  const count=await page.locator('.interactive-demo').count();
  await page.route('**/api/agent/chat/stream',async route=>{await new Promise(resolve=>setTimeout(resolve,1200));await route.continue().catch(()=>{});});
  await region().getByRole('button',{name:'计算演示需求'}).click();
  await region().getByRole('button',{name:'取消计算'}).click();
  await region().getByRole('status').filter({hasText:'取消'}).waitFor();
  check(await page.locator('.interactive-demo').count()===count,'cancel produces no result');
  await page.unroute('**/api/agent/chat/stream');
  await page.route('**/api/agent/chat/stream',route=>route.abort('failed'));
  await region().getByRole('button',{name:'计算演示需求'}).click();
  await region().getByRole('alert').waitFor();
  check(await region().innerText().then(t=>t.includes('1,907.12')),'failure preserves previous result');
  await page.screenshot({path:'output/playwright/20261015-mrp-failure.png'});
  await page.unroute('**/api/agent/chat/stream');
  await page.getByRole('button',{name:'关闭演示详情'}).click();
  const prior=await page.locator('.interactive-demo').count();
  await ask('请执行真实订单 Z9900003 重排');
  await page.getByText('真实插单、重排和 MRP 运算尚未接入；未执行任何业务操作，也未用模拟结果代替。',{exact:true}).waitFor();
  check(await page.locator('.interactive-demo').count()===prior,'no synthetic card for real request');
  await page.screenshot({path:'output/playwright/20261015-real-operation-refusal.png'});
  return {status:'PASS',checks:['same-order MRP layers','units','quantity change','none/stock/supply/late','repeat no decrement','cancellation','controlled network failure retains result','real-operation refusal']};
}
