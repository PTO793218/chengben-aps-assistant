async (page) => {
  page.setDefaultTimeout(150000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const check=(v,m)=>{if(!v)throw Error(m);};
  const ask=async(text)=>{await page.getByRole('textbox',{name:'输入问题',exact:true}).fill(text);await page.getByRole('button',{name:'发送消息',exact:true}).click();};
  await page.getByRole('button',{name:'新建对话',exact:true}).click();
  await page.getByRole('button',{name:'新对话查看历史演示快照',exact:true}).click();
  await page.locator('.suggestion-grid button').first().waitFor();
  check(await page.locator('.suggestion-grid button').count()===5,'three query plus two demo entries');
  check(await page.locator('.suggestion-grid').getByRole('button',{name:/演示订单 Z9900006 怎么安排|哪些订单已经形成派工/}).count()===0,'single-order and dispatch shortcuts removed');
  await page.screenshot({path:'output/playwright/20261015-home-six-entries.png'});
  await ask('查询演示订单 Z9900006 的排程');
  await page.locator('.aps-card.compact').getByRole('button',{name:'展开查看'}).last().waitFor({timeout:150000});
  await page.locator('.aps-card.compact').getByRole('button',{name:'展开查看'}).last().click();
  await page.getByRole('region',{name:'APS 分析视图',exact:true}).waitFor();
  check(await page.locator('.aps-gantt tbody').innerText().then(t=>t.includes('Z9900006')&&!t.includes('Z9900003')),'existing schedule order isolation');
  await page.screenshot({path:'output/playwright/20261015-six-entry-query-schedule.png'});
  await page.getByRole('button',{name:'关闭分析视图'}).click();
  await ask('演示订单 Z9900006 的物料齐套状态如何？');
  await page.locator('.material-card.compact').getByRole('button',{name:'查看详情'}).last().waitFor({timeout:150000});
  await page.locator('.material-card.compact').getByRole('button',{name:'查看详情'}).last().click();
  await page.getByRole('region',{name:'订单物料齐套详情',exact:true}).waitFor();
  check(await page.getByRole('region',{name:'订单物料齐套详情',exact:true}).innerText().then(t=>t.includes('Z9900006')),'existing material detail');
  await page.screenshot({path:'output/playwright/20261015-six-entry-query-material.png'});
  await page.getByRole('button',{name:'关闭物料齐套详情'}).click();
  await ask('演示订单 Z9900006 派工了吗？');
  await page.locator('.order-dispatch-card.compact').getByRole('button',{name:'查看详细'}).waitFor({timeout:150000});
  await page.locator('.order-dispatch-card.compact').getByRole('button',{name:'查看详细'}).click();
  await page.getByRole('region',{name:'订单派工在制核对详情',exact:true}).waitFor();
  check(await page.getByRole('region',{name:'订单派工在制核对详情',exact:true}).innerText().then(t=>t.includes('Z9900006')),'existing dispatch detail');
  await page.screenshot({path:'output/playwright/20261015-six-entry-query-dispatch.png'});
  await page.getByRole('button',{name:'关闭订单派工在制核对详情'}).click();
  check(await page.locator('.interactive-demo').count()===0,'new conversation does not inherit demo plan/results');
  check(errors.length===0,'no browser JavaScript exceptions: '+errors.join(';'));
  return {status:'PASS',checks:['5 entries','single-order and dispatch shortcuts removed','model schedule and matrix from chat','material and detail','dispatch and detail from chat','new conversation isolation','no JavaScript exceptions'],screenshots:4};
}
