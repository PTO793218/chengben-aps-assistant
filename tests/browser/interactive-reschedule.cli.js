async (page) => {
  page.setDefaultTimeout(150000);
  const check=(value,message)=>{if(!value)throw new Error(message);};
  await page.setViewportSize({width:1440,height:1080});
  await page.getByRole('button',{name:'新建对话',exact:true}).click();
  await page.locator('.suggestion-grid button').first().waitFor();
  await page.locator('.suggestion-grid button').first().click();
  const setup=page.locator('.interactive-demo').last();
  await setup.getByLabel('目标演示订单').waitFor();
  if(!(await setup.locator('.demo-execution').innerText()).includes('大模型已参与'))throw Error('preparation must invoke model');
  check(await setup.getByRole('button',{name:'按此顺序试排'}).isDisabled(),'missing order requires explicit selection');
  await setup.getByLabel('目标演示订单').selectOption('Z9900003');
  await setup.getByRole('button',{name:'取消此次操作'}).click();
  await setup.getByRole('status').filter({hasText:'取消'}).waitFor();
  await setup.getByRole('button',{name:'按此顺序试排'}).click();
  await page.locator('.interactive-demo').last().getByRole('button',{name:'查看演示详情'}).waitFor();
  await page.locator('.interactive-demo').last().getByRole('button',{name:'查看演示详情'}).click();
  const region=page.getByRole('region',{name:'操作演示详情'});
  check(await region.locator('.demo-execution').innerText().then(t=>t.includes('大模型已参与')),'confirmed calculation invoked model');
  check(await region.locator('.aps-gantt').count()===2,'before/after matrices');
  check(await region.locator('.aps-gantt').first().locator('tbody tr').count()===9,'whole batch has 9 operation rows');
  await region.locator('.demo-gantts').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/20261015-reschedule-matrices.png'});
  await region.getByLabel('需求版本').selectOption('261015002');
  await region.getByRole('button',{name:'按此顺序试排'}).click();
  await region.getByRole('alert').filter({hasText:'已下达'}).waitFor();
  check(await region.locator('.demo-table-wrap').first().innerText().then(t=>t.includes('3 → 1')),'old result retained after refusal');
  await page.screenshot({path:'output/playwright/20261015-released-refusal.png'});
  await region.getByRole('button',{name:'采用此演示方案'}).click();
  await page.getByText('已在需求版本 261015001（模拟）内采用试排方案',{exact:false}).waitFor();
  const oldTable=await page.locator('.interactive-demo').nth(1).locator('table').innerText();
  await page.getByRole('textbox',{name:'输入问题',exact:true}).fill('订单 Z9900003 怎么安排？');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await page.locator('.aps-card.compact').filter({has:page.getByRole('button',{name:'展开查看'})}).last().getByText('需求版本 261015001',{exact:false}).first().waitFor();
  check(await page.locator('.aps-card.compact').filter({has:page.getByRole('button',{name:'展开查看'})}).last().innerText().then(t=>t.includes('2026-10-02')),'adopted plan query');
  check(await page.locator('.interactive-demo').nth(1).locator('table').innerText()===oldTable,'historical table immutable');
  await page.screenshot({path:'output/playwright/20261015-adopted-query.png'});
  await page.reload();
  await page.locator('.aps-card.compact').filter({has:page.getByRole('button',{name:'展开查看'})}).last().getByText('需求版本 261015001',{exact:false}).first().waitFor();
  check(await page.locator('.interactive-demo').nth(1).getByRole('button',{name:'采用此演示方案'}).isDisabled(),'repeat adoption disabled after reload');
  await page.getByRole('button',{name:'恢复初始演示方案'}).last().click();
  await page.getByText('已恢复需求版本 261015001（模拟）的初始顺序',{exact:false}).waitFor();
  check(await page.locator('.interactive-demo').nth(1).locator('table').innerText()===oldTable,'old table preserved after restore');
  await page.locator('.interactive-demo').nth(1).getByRole('button',{name:'查看演示详情'}).click();
  check(await page.getByRole('region',{name:'操作演示详情'}).locator('.demo-table-wrap').first().innerText()===oldTable,'reopen uses old payload');
  await page.screenshot({path:'output/playwright/20261015-historical-result.png'});
  await page.getByRole('button',{name:'关闭演示详情'}).click();
  return {status:'PASS',checks:['explicit order selection','cancel before preview','whole-batch matrices','released refusal','adoption','current query','reload','duplicate prevention','restore','immutable historical detail']};
}
