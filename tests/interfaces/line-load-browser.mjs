import { chromium } from '../../web-frontend/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1800}});
 const errors=[];let requests=0;
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.url().includes('/api/agent/'))requests++;});
 await page.goto(process.env.BASE_URL||'http://localhost:19440');
 await page.getByRole('textbox',{name:'输入问题'}).fill('查询真实订单 Z9900027 的排程，版本260904001');
 await page.getByRole('button',{name:'发送消息',exact:true}).click();
 await page.locator('.line-load-panel').waitFor({timeout:150000});
 const before=requests;
 assert.ok(await page.locator('.aps-gantt-preview').isVisible());
 assert.equal(await page.locator('.order-stage-list').count(),0);
 assert.equal(await page.locator('.load-table tbody tr').count(),3);
 assert.match(await page.locator('.load-table').innerText(),/903.94/);
 assert.match(await page.locator('.load-table').innerText(),/224.3/);
 fs.mkdirSync('temp/verification',{recursive:true});
 await page.locator('.line-load-panel').screenshot({path:'temp/verification/line-load-month.png'});
 await page.locator('.load-exceptions button').first().click();
 assert.equal(await page.getByRole('combobox',{name:'负载粒度',exact:true}).inputValue(),'day');
 await page.getByRole('combobox',{name:'负载粒度',exact:true}).selectOption('day');
 await page.getByRole('combobox',{name:'负载统计期间',exact:true}).selectOption('2026-09-20');
 const dayRows=await page.locator('.load-table tbody tr').allTextContents();
 assert.ok(dayRows.some(r=>r.includes('cxcx2')&&r.includes('无工作工时')));
 assert.ok(dayRows.some(r=>r.includes('S09-3')&&r.includes('8 h')));
 await page.getByRole('combobox',{name:'负载粒度',exact:true}).selectOption('year');
 assert.match(await page.locator('.load-table').innerText(),/缺日历/);
 await page.getByRole('combobox',{name:'负载粒度',exact:true}).selectOption('month');
 await page.getByRole('combobox',{name:'负载统计期间',exact:true}).selectOption('2026-09');
 await page.locator('.load-table button').filter({hasText:'S09-3'}).click();
 assert.match(await page.locator('.load-trend-heading').innerText(),/S09-3/);
 assert.ok(await page.locator('.load-trend canvas').isVisible());
 await page.getByRole('button',{name:/展开查看/}).click();
 await page.locator('.aps-analysis-viewer').waitFor();
 assert.equal(await page.locator('.aps-gantt tbody tr').count(),3);
 assert.deepEqual((await page.locator('.aps-gantt-slot span').allTextContents()).sort(),['1912','2600','2600','688'].sort());
 assert.equal(await page.locator('.aps-detail tbody tr').count(),4);
 await page.locator('.aps-analysis-viewer .line-load-panel').screenshot({path:'temp/verification/line-load-expanded.png'});
 await page.getByRole('button',{name:'关闭分析视图'}).click();
 assert.equal(requests,before,'UI changes must not invoke backend/model');
 await page.reload();await page.locator('.line-load-panel').waitFor();
 assert.equal(await page.locator('.load-table tbody tr').count(),3);
 await page.setViewportSize({width:390,height:1800});
 assert.ok(await page.locator('.load-chart-scroll').first().evaluate(el=>el.getBoundingClientRect().width<390 && el.scrollWidth>=520));
 await page.locator('.line-load-panel').screenshot({path:'temp/verification/line-load-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: real model -> visible matrix + 3-line load; year/month/day, daily capacity, line trend, expand/back, unchanged 4 records, no refetch, history, mobile, no page errors.');
} finally {await browser.close();}
